import assert from 'node:assert/strict'
import { createServer } from 'node:http'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { build } from 'esbuild'
import { chromium } from 'playwright'

const outdir = resolve('artifacts/kafka-readonly-ui')
await mkdir(outdir, { recursive: true })
await build({ entryPoints: ['test/fixtures/kafka-readonly-ui.tsx'], bundle: true, format: 'esm', outdir, entryNames: 'fixture', assetNames: 'fixture' })
await writeFile(resolve(outdir, 'index.html'), '<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width"><link rel="stylesheet" href="/fixture.css"><style>html,body,#app{height:100%;margin:0}</style></head><body><div id="app"></div><script type="module" src="/fixture.js"></script></body></html>')
const server = createServer(async (request, response) => {
  const path = new URL(request.url, 'http://localhost').pathname
  try {
    const file = resolve(outdir, '.' + (path === '/' ? '/index.html' : path))
    if (!file.startsWith(outdir + '\\') && !file.startsWith(outdir + '/')) { response.writeHead(404); response.end(); return }
    const body = await readFile(file)
    response.writeHead(200, { 'Content-Type': path.endsWith('.css') ? 'text/css' : path.endsWith('.js') ? 'text/javascript' : 'text/html' }); response.end(body)
  } catch { response.writeHead(404); response.end() }
})
await new Promise(done => server.listen(0, '127.0.0.1', done))
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const checks = [], errors = []
try {
  for (const width of [420, 768, 1200]) for (const colorScheme of ['dark', 'light']) {
    const page = await browser.newPage({ viewport: { width, height: 800 }, colorScheme, acceptDownloads: true })
    page.setDefaultTimeout(8000)
    page.on('pageerror', error => errors.push(error.message))
    try {
      await page.goto(`http://127.0.0.1:${server.address().port}/`)
      await page.evaluate(theme => { document.documentElement.dataset.theme = theme }, colorScheme)
      const workspace = page.getByLabel('Kafka 工作区', { exact: true })
      await workspace.waitFor()
      await workspace.locator('.db-search-tree').waitFor({ state: 'attached' })
      const topicDrawer = workspace.getByRole('button', { name: '打开 Topic 列表', exact: true })
      if (await topicDrawer.isVisible()) await topicDrawer.click()
      await workspace.getByRole('button', { name: 'orders', exact: true }).waitFor()
      await workspace.getByRole('tab', { name: '查询', exact: true }).click()
      const editor = () => workspace.getByLabel('Kafka 命令')
      const names = async () => {
        await editor().fill('DESCRIBE '); await editor().press('End'); await editor().press('Control+Shift+Space')
        await page.locator('.cm-tooltip-autocomplete').getByText('orders', { exact: true }).waitFor()
        const before = await page.evaluate(() => window.kafkaFixture.state.runs)
        await page.locator('.cm-tooltip-autocomplete').getByText('orders', { exact: true }).click()
        assert.equal(await editor().innerText(), 'DESCRIBE "orders"')
        assert.equal(await page.evaluate(() => window.kafkaFixture.state.runs), before)
      }
      await names()
      await editor().fill('PEE'); await editor().press('End'); await editor().press('Control+Shift+Space')
      await page.locator('.cm-tooltip-autocomplete').getByText('PEEK', { exact: true }).waitFor()
      await editor().press('ArrowDown'); await editor().press('Enter')
      assert.equal(await editor().innerText(), 'PEEK')
      assert.equal(await page.evaluate(() => window.kafkaFixture.state.runs), 0)
      await editor().dispatchEvent('compositionstart', { data: '' })
      await editor().press('Enter')
      assert.equal(await page.evaluate(() => window.kafkaFixture.state.runs), 0)
      await editor().dispatchEvent('compositionend', { data: '' })
      await editor().fill('PEEK "orders" PARTITION 0 FROM LATEST LIMIT 2'); await editor().press('ControlOrMeta+Enter')
      await workspace.getByRole('button', { name: '查看 JSON' }).click()
      await workspace.getByText('"a": 1', { exact: false }).waitFor()
      await workspace.getByRole('button', { name: '查看原文' }).click()
      const download = page.waitForEvent('download')
      await workspace.getByRole('button', { name: '导出当前结果 JSON' }).click()
      const file = await (await download).path()
      const exported = JSON.parse(await readFile(file, 'utf8'))
      assert.equal(exported.result.complete, false); assert.equal(exported.result.messages[1].value.length, 99999)
      assert.equal(exported.result.messages[1].value.base64, '/w==')
      await editor().fill('TOPICS SEARCH "order"'); await editor().press('ControlOrMeta+Enter')
      await workspace.getByRole('button', { name: '下一页草稿' }).click()
      assert.equal(await editor().innerText(), 'TOPICS SEARCH "order" CURSOR 100')
      assert.equal(await page.evaluate(() => window.kafkaFixture.state.runs), 2)
      await workspace.getByRole('tab', { name: '总览', exact: true }).click()
      if (await topicDrawer.isVisible()) await topicDrawer.click()
      await workspace.getByRole('button', { name: 'orders', exact: true }).click()
      await workspace.getByRole('button', { name: '发布单条消息草稿' }).click()
      await workspace.getByRole('tab', { name: '查询', exact: true }).click()
      assert.equal(await editor().innerText(), 'PRODUCE {"topic":"orders","value":""}')
      let publishConfirmation = ''
      page.once('dialog', async dialog => { publishConfirmation = dialog.message(); await dialog.accept() })
      await editor().fill('PRODUCE {"topic":"orders","value":"hello"}')
      await editor().press('ControlOrMeta+Enter')
      await workspace.getByText('Broker 已确认发布到 orders', { exact: false }).waitFor()
      assert.match(publishConfirmation, /orders/)
      assert.equal(await page.evaluate(() => window.kafkaFixture.state.runs), 3)
      await workspace.getByRole('tab', { name: 'AI Query', exact: true }).click()
      await editor().fill('PRODUCE {"topic":"orders","value":"hello"}')
      let aiConfirmation = ''
      page.once('dialog', async dialog => { aiConfirmation = dialog.message(); await dialog.dismiss() })
      await workspace.getByRole('button', { name: '执行当前内容' }).click()
      assert.match(aiConfirmation, /orders/)
      assert.equal(await page.evaluate(() => window.kafkaFixture.state.runs), 3)
      for (const tab of ['AI Query', '经验库']) { await workspace.getByRole('tab', { name: tab, exact: true }).click(); await names() }
      await workspace.getByRole('tab', { name: '总览', exact: true }).click()
      await page.getByRole('button', { name: '消费组视图', exact: true }).click()
      await page.waitForFunction(() => document.querySelector('.db-search-tree-head > span')?.textContent === '消费组')
      await workspace.locator('button.db-tree-label[title="billing"]').waitFor({ state: 'attached' })
      if (width === 420) await workspace.getByRole('button', { name: '打开消费组列表', exact: true }).waitFor()
      const groupDrawer = workspace.getByRole('button', { name: '打开消费组列表', exact: true })
      if (await groupDrawer.isVisible()) await groupDrawer.click()
      await workspace.getByRole('button', { name: 'billing', exact: true }).waitFor()
      await page.evaluate(() => window.kafkaFixture.delayChildren())
      await workspace.getByRole('button', { name: '展开 billing', exact: true }).click()
      await page.waitForFunction(() => window.kafkaFixture.state.childCalls === 1)
      await page.getByRole('button', { name: '刷新作用域', exact: true }).click()
      await page.evaluate(() => window.kafkaFixture.releaseOld())
      await workspace.locator('button.db-tree-label[title="billing"]').waitFor({ state: 'attached' })
      if (await groupDrawer.isVisible()) await groupDrawer.click()
      await workspace.getByRole('button', { name: 'billing', exact: true }).waitFor()
      assert.equal(await page.getByText('STALE_OLD_TOPIC').count(), 0)
      for (const tab of ['查询', 'AI Query', '经验库']) {
        await workspace.getByRole('tab', { name: tab, exact: true }).click()
        await editor().fill('GROUP '); await editor().press('End'); await editor().press('Control+Shift+Space')
        await page.locator('.cm-tooltip-autocomplete').getByText('billing', { exact: true }).click()
        assert.equal(await editor().innerText(), 'GROUP "billing"')
        assert.equal(await page.evaluate(() => window.kafkaFixture.state.runs), 3)
      }
      await workspace.getByRole('tab', { name: '查询', exact: true }).click()
      await page.getByRole('button', { name: '模拟重连', exact: true }).click()
      await workspace.getByRole('tab', { name: '查询', exact: true }).click()
      await editor().fill('DESCRIBE "ord'); await editor().press('End'); await editor().press('Control+Shift+Space')
      await page.waitForTimeout(150)
      assert.equal(await page.locator('.cm-tooltip-autocomplete').count(), 0)
      await page.screenshot({ path: resolve(outdir, `${width}-${colorScheme}.png`) })
      checks.push({ width, colorScheme, cachedNames: true, groupNamesInThreeEditors: true, keyboard: true, composition: true, acceptDoesNotRun: true, json: true, export: true, nextPageDraft: true, publishDraftAndReceipt: true, staleChildren: true, reconnect: true })
    } catch (error) {
      await page.screenshot({ path: resolve(outdir, 'failure.png') })
      await writeFile(resolve(outdir, 'failure.json'), JSON.stringify({ width, colorScheme, message: error.message, text: await page.locator('body').innerText(), fixture: await page.evaluate(() => window.kafkaFixture?.state), html: await page.locator('.db-search-tree').innerHTML().catch(() => ''), errors }, null, 2))
      throw error
    } finally { await page.close() }
  }
  const repairPage = await browser.newPage({ viewport: { width: 1200, height: 800 } })
  repairPage.setDefaultTimeout(8000)
  repairPage.on('pageerror', error => errors.push(error.message))
  try {
    await repairPage.goto(`http://127.0.0.1:${server.address().port}/`)
    const workspace = repairPage.getByLabel('Kafka 工作区', { exact: true })
    await workspace.waitFor()
    const editor = workspace.getByLabel('Kafka 命令')
    await workspace.getByText('创建 SIT 测试 Topic', { exact: true }).click()
    await workspace.getByLabel('名称', { exact: true }).fill('dsh-test-ui')
    await workspace.getByRole('button', { name: '填入创建草稿' }).click()
    await workspace.getByRole('tab', { name: '查询', exact: true }).click()
    assert.match(await editor.innerText(), /^CREATE_TOPIC /)
    await workspace.getByRole('tab', { name: '总览', exact: true }).click()
    await workspace.getByRole('button', { name: 'orders', exact: true }).click()
    await workspace.getByText('发布单条消息', { exact: true }).click()
    await workspace.getByLabel('Value 格式').selectOption('base64')
    await workspace.getByLabel('Value', { exact: true }).fill('AAE=')
    await workspace.getByRole('button', { name: '填入发布草稿' }).click()
    await workspace.getByRole('tab', { name: '查询', exact: true }).click()
    assert.match(await editor.innerText(), /"base64":"AAE="/)
    await workspace.getByRole('tab', { name: '总览', exact: true }).click()
    await workspace.getByRole('button', { name: 'orders', exact: true }).click()
    await workspace.getByText('限量批量发布', { exact: true }).click()
    await workspace.getByRole('button', { name: '填入批量草稿' }).click()
    await workspace.getByRole('tab', { name: '查询', exact: true }).click()
    assert.match(await editor.innerText(), /^PRODUCE_BATCH /)
    let confirmation = ''
    repairPage.once('dialog', async dialog => { confirmation = dialog.message(); await dialog.accept() })
    await editor.press('ControlOrMeta+Enter')
    await workspace.getByText('第 1 条 · 分区 0', { exact: false }).waitFor()
    assert.match(confirmation, /orders/)
    await workspace.getByRole('button', { name: '回读' }).click()
    assert.equal(await editor.innerText(), 'PEEK "orders" PARTITION 0 FROM OFFSET 43 LIMIT 1')
    checks.push({ repairForms: true, binaryDraft: true, batchConfirmation: true, batchReceiptPeek: true })
  } finally { await repairPage.close() }
  assert.deepEqual(errors, [])
  await writeFile(resolve(outdir, 'report.json'), JSON.stringify({ status: 'PASS', checks, pageErrors: errors }, null, 2))
  console.log(JSON.stringify({ status: 'PASS', cases: checks.length, report: 'artifacts/kafka-readonly-ui/report.json' }))
} finally { await browser.close(); await new Promise(done => server.close(done)) }
