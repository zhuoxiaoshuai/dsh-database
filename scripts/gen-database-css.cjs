'use strict'
const fs = require('node:fs')
const path = require('node:path')

const root = path.resolve(__dirname, '..')
const input = path.join(root, 'src', 'client', 'style.css')
const output = path.join(root, 'src', 'client', 'style-css.ts')
const { defaultThemeCss } = require('../src/client/workspace/parts/theme/theme-tokens.ts')
const themeCss = defaultThemeCss()
fs.writeFileSync(path.join(root, 'src', 'client', 'theme.css'), themeCss)
const css = themeCss + fs.readFileSync(input, 'utf8').replace("@import './theme.css';", '')
const generated = `// Generated by scripts/gen-database-css.cjs.\nexport const databaseCss = ${JSON.stringify(css)}\n`
if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== generated) fs.writeFileSync(output, generated)
console.log(`[gen-database-css] embedded ${Buffer.byteLength(css)} bytes`)
